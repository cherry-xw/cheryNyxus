import { describe, expect, it } from 'vitest'
import { randomBytes } from 'node:crypto'
import sharp from 'sharp'
import { prepareImage } from '@/service/media/prepareImage.js'

describe('模型图片格式与每图硬上限', () => {
  it.each(['jpeg', 'png', 'webp'] as const)('合规 %s 原图即使质量上限为 1 也复用同一 buffer', async (format) => {
    const data = await sharp({ create: { width: 48, height: 24, channels: 3, background: '#246898' } }).toFormat(format).toBuffer()
    const result = await prepareImage(data, { quality: 1 }, { formats: [`image/${format}`] })
    expect(result.data).toBe(data)
    expect(result).toMatchObject({ width: 48, height: 24, mimeType: `image/${format}` })
  })
  it.each(['jpeg', 'webp'] as const)('小图转换 %s 使用显式编码上限，不按像素额外降质；超限才继续降低', async (format) => {
    const data = await sharp(randomBytes(96 * 48 * 3), { raw: { width: 96, height: 48, channels: 3 } }).png().toBuffer()
    const original = Buffer.from(data)
    const encode = (quality: number) => format === 'jpeg' ? sharp(data).jpeg({ quality }).toBuffer() : sharp(data).webp({ quality, alphaQuality: 100 }).toBuffer()
    const ceiling = await encode(73)
    const lower = await encode(53)
    expect(lower.length).toBeLessThan(ceiling.length)
    const converted = await prepareImage(data, { quality: 73 }, { formats: [`image/${format}`] })
    expect(converted.data).toEqual(ceiling)
    expect(converted).toMatchObject({ width: 96, height: 48 })
    const compressed = await prepareImage(data, { quality: 73, maxBytes: lower.length }, { formats: [`image/${format}`] })
    expect(compressed.data).toEqual(lower)
    expect(compressed.data.length).toBeLessThanOrEqual(lower.length)
    expect(compressed).toMatchObject({ width: 96, height: 48 })
    expect(data).toEqual(original)
  })
  it('PNG 转换不使用有损 quality，质量值不同不改变无损编码', async () => {
    const data = await sharp({ create: { width: 48, height: 24, channels: 3, background: '#246898' } }).tiff().toBuffer()
    const low = await prepareImage(data, { quality: 1 }, { formats: ['image/png'] })
    const high = await prepareImage(data, { quality: 100 }, { formats: ['image/png'] })
    expect(low.data).toEqual(high.data)
    expect(low).toMatchObject({ width: 48, height: 24 })
  })
  it('可读元数据的截断原图不能直接复用；服务原始字节限制独立执行', async () => {
    const data = await sharp(randomBytes(96 * 48 * 3), { raw: { width: 96, height: 48, channels: 3 } }).png().toBuffer()
    const truncated = data.subarray(0, 100)
    expect((await sharp(truncated).metadata()).format).toBe('png')
    await expect(prepareImage(truncated, {}, { formats: ['image/png'] })).rejects.toThrow()
    const result = await prepareImage(data, {}, { formats: ['image/png'], maxBytes: 1000 })
    expect(result.data).not.toBe(data)
    expect(result.data.length).toBeLessThanOrEqual(1000)
    expect(result.width / result.height).toBe(2)
  })
  it('默认 5 MB 对真实超过 5,000,000 字节的 PNG 生效', async () => {
    const data = await sharp(randomBytes(1400 * 1400 * 3), { raw: { width: 1400, height: 1400, channels: 3 } }).png().toBuffer()
    expect(data.length).toBeGreaterThan(5000000)
    const result = await prepareImage(data, {}, { formats: ['image/png'] })
    expect(result.data.length).toBeLessThanOrEqual(5000000)
    expect(result.width / result.height).toBe(1)
  })
  it('真实编码缩小到硬上限，输出尺寸与 MIME 一致；原始 buffer 不变', async () => {
    const data = await sharp(randomBytes(512 * 512 * 3), { raw: { width: 512, height: 512, channels: 3 } }).png().toBuffer()
    const original = Buffer.from(data)
    const result = await prepareImage(data, { maxBytes: 8000 }, { formats: ['image/webp'] })
    expect(result.data.length).toBeLessThanOrEqual(8000)
    expect(result.mimeType).toBe('image/webp')
    expect(await sharp(result.data).metadata()).toMatchObject({ width: result.width, height: result.height, format: 'webp' })
    expect(data).toEqual(original)
  })
  it('透明静态 TIFF 转为允许的 PNG，不能转为仅支持 JPEG', async () => {
    const data = await sharp({ create: { width: 32, height: 16, channels: 4, background: { r: 1, g: 2, b: 3, alpha: 0.5 } } }).tiff({ compression: 'lzw' }).toBuffer()
    const result = await prepareImage(data, {}, { formats: ['image/png'] })
    expect(result.mimeType).toBe('image/png')
    expect((await sharp(result.data).metadata()).hasAlpha).toBe(true)
    await expect(prepareImage(data, {}, { formats: ['image/jpeg'] })).rejects.toThrow('透明')
  })
  it('合法小图不为追求目标体积反复压缩；服务 base64 限额独立于原始字节上限', async () => {
    const data = await sharp({ create: { width: 64, height: 32, channels: 3, background: '#123456' } }).png().toBuffer()
    expect((await prepareImage(data, {}, { formats: ['image/png'] })).data).toEqual(data)
    const result = await prepareImage(data, { maxBytes: 5000000 }, { formats: ['image/png'], maxBase64Bytes: 160 })
    expect(4 * Math.ceil(result.data.length / 3)).toBeLessThanOrEqual(160)
  })
  it('不可达、无效输入、未知格式清单明确失败，无超限原件回退', async () => {
    const data = await sharp({ create: { width: 10, height: 10, channels: 3, background: '#ffffff' } }).png().toBuffer()
    await expect(prepareImage(data, { maxBytes: 1 }, { formats: ['image/png'] })).rejects.toThrow('硬上限')
    await expect(prepareImage(Buffer.from('not image'), {}, { formats: ['image/png'] })).rejects.toThrow()
    await expect(prepareImage(data, {}, {})).rejects.toThrow('未声明')
  })
  it('动画默认不取首帧，显式完整动画支持才允许保留全部帧', async () => {
    const pixels = Buffer.concat([Buffer.alloc(8 * 8 * 3, 30), Buffer.alloc(8 * 8 * 3, 200)])
    const data = await sharp(pixels, { raw: { width: 8, height: 16, channels: 3, pageHeight: 8 } }).gif({ delay: [100, 200], loop: 2 }).toBuffer()
    expect((await sharp(data, { animated: true }).metadata()).pages).toBe(2)
    for (const animation of ['unknown', 'first-frame', 'unsupported'] as const) await expect(prepareImage(data, {}, { formats: ['image/gif'], animation })).rejects.toThrow('动画')
    const result = await prepareImage(data, { maxEdge: 4 }, { formats: ['image/gif'], animation: 'supported' })
    expect(result.preservedAnimation).toBe(true)
    expect(await sharp(result.data, { animated: true }).metadata()).toMatchObject({ pages: 2, delay: [100, 200], loop: 2 })
  })
})
