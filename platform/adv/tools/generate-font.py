#!/usr/bin/env python3
"""Generate cheryNyxus Basic; explicit font/tool paths, no downloads."""
import argparse
import hashlib
import pathlib
import subprocess
import json

FONT_SHA256 = 'c0aa89a70f92a820ff95490fea6d472cd19621a71c9a748a4950eb2eafe6438e'
SOURCE_COMMIT = 'a8b073bbf80f7226af03abeeb31e27017d5e3f67'
ROOT = pathlib.Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser()
p.add_argument('--font', type=pathlib.Path, required=True)
p.add_argument('--converter', type=pathlib.Path, required=True)
p.add_argument('--output', type=pathlib.Path, default=ROOT / 'main/fonts/adv_font_basic.c')
a = p.parse_args()
data = a.font.read_bytes()
actual_sha256 = hashlib.sha256(data).hexdigest()
actual_blob = hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()
if (len(data), actual_blob, actual_sha256) != (8331636, 'c13789be298515b27311fd017aaa32a3c41d42b9', FONT_SHA256):
    p.error(f'font source mismatch: size={len(data)}, git_blob={actual_blob}, sha256={actual_sha256}; expected fixed upstream complete blob')
assert json.loads((a.converter.parent / 'package.json').read_text())['version'] == '1.5.3', 'converter version mismatch'
chars = ''.join(sorted(set((ROOT / 'main/fonts/basic-characters.txt').read_text().strip())))
subprocess.run(['node', str(a.converter), '--font', str(a.font), '--size', '16', '--bpp', '2', '--format', 'lvgl', '--range', '0x20-0x7e', '--symbols', chars, '--no-compress', '--no-kerning', '--lv-include', 'lvgl.h', '--lv-font-name', 'adv_font_basic', '-o', str(a.output)], check=True)
content = a.output.read_text()
# Tool embeds invocation paths: remove machine-specific command comment.
start = content.index('/**')
end = content.index('*/', start) + 2
content = content[:start] + f'/* cheryNyxus Basic; SIL OFL 1.1; Copyright 2014-2021 Adobe.\n * Derived from source-han-sans 2.004R ({SOURCE_COMMIT}).\n * See OFL.txt; generated by tools/generate-font.py / lv_font_conv 1.5.3. */' + content[end:]
a.output.write_text(content)
print('font generated:', a.output, 'bytes:', a.output.stat().st_size, 'glyphs:', len(set(chars) | set(map(chr, range(32, 127)))))
